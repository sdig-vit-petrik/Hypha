//! Emitting C++ headers from a message specification.

use std::collections::BTreeSet;

use crate::put;
use hypha_msgdef::constant::{ConstantValue, constant_value};
use hypha_msgdef::resolve::{ResolveError, ServiceIdentity, SpecSet, definition_text};
use hypha_msgdef::spec::{Constant, Field, FieldType, MessageSpec, Multiplicity, ServiceSpec};

/// The three C++ files generated for one service.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ServiceOutput {
    /// Request message header.
    pub request: String,
    /// Response message header.
    pub response: String,
    /// Service wrapper header.
    pub service: String,
}

/// Emit request, response, and service wrapper headers. Each half carries its
/// definition text and its own MD5.
///
/// # Errors
/// Returns a [`ResolveError`] when a request or response type, or a type it
/// reaches, has no definition in `specs`.
pub fn emit_service(
    specs: &SpecSet,
    spec: &ServiceSpec,
    identity: &ServiceIdentity,
) -> Result<ServiceOutput, ResolveError> {
    let request_definition = definition_text(specs, &spec.request.type_name)?;
    let response_definition = definition_text(specs, &spec.response.type_name)?;
    let request =
        emit_message_with_definition(&spec.request, &identity.request, &request_definition);
    let response =
        emit_message_with_definition(&spec.response, &identity.response, &response_definition);
    let package = &spec.type_name.package;
    let name = &spec.type_name.name;
    let md5 = &identity.service;
    let service = format!(
        "// Generated by hypha_msggen. Do not edit.\n#pragma once\n\n#include <{package}/{name}Request.h>\n#include <{package}/{name}Response.h>\n\nnamespace {package} {{\nstruct {name} {{\n  using Request = {name}Request;\n  using Response = {name}Response;\n  static constexpr const char* MD5 = \"{md5}\";\n}};\n}}  // namespace {package}\n"
    );
    Ok(ServiceOutput { request, response, service })
}

/// Emits the C++ header for one message type, with the [`definition_text`] of `spec`.
///
/// # Errors
/// Returns a [`ResolveError`] when `spec`, or a type it reaches, has no
/// definition in `specs`.
pub fn emit_message(
    specs: &SpecSet,
    spec: &MessageSpec,
    md5: &str,
) -> Result<String, ResolveError> {
    let definition = definition_text(specs, &spec.type_name)?;
    Ok(emit_message_with_definition(spec, md5, &definition))
}

/// Emits the C++ header for one message type with an explicit definition text.
#[must_use]
pub fn emit_message_with_definition(spec: &MessageSpec, md5: &str, definition: &str) -> String {
    let mut output = String::new();
    emit_preamble(&mut output, spec);
    emit_struct(&mut output, spec, md5);
    emit_message_traits(&mut output, spec, md5, definition);
    emit_serializer(&mut output, spec);
    emit_loaned_field(&mut output, spec);
    emit_view(&mut output, spec);
    output
}

fn emit_preamble(output: &mut String, spec: &MessageSpec) {
    put(
        output,
        format_args!(
            "// Generated from the {} definition. Do not edit.\n\n#pragma once\n\n",
            spec.type_name.full()
        ),
    );
    for header in ["array", "cstdint", "memory", "string", "type_traits", "vector"] {
        put(output, format_args!("#include <{header}>\n"));
    }
    output.push_str(
        "\n#include <ros/message_traits.h>\n#include <ros/serialization.h>\n#include <hypha_msgs/ros_time.h>\n",
    );

    let nested_types: BTreeSet<_> = spec
        .fields
        .iter()
        .filter_map(|field| match &field.field_type {
            FieldType::Message(type_name) => Some(type_name),
            _ => None,
        })
        .collect();
    for type_name in nested_types {
        put(output, format_args!("#include <{}/{}.h>\n", type_name.package, type_name.name));
    }
    output.push('\n');
}

fn emit_struct(output: &mut String, spec: &MessageSpec, md5: &str) {
    let package = &spec.type_name.package;
    let name = &spec.type_name.name;
    put(output, format_args!("namespace {package} {{\n\nstruct {name} {{\n"));
    for constant in &spec.constants {
        emit_constant(output, constant);
    }
    for field in &spec.fields {
        put(
            output,
            format_args!(
                "  {} {}{{}};\n",
                cpp_field_type(&field.field_type, field.multiplicity),
                field_name_safe(&field.name)
            ),
        );
    }
    // The member types under the names ROS 1 and ROS 2 generated C++ gives them.
    if !spec.fields.is_empty() {
        output.push('\n');
    }
    for field in &spec.fields {
        put(
            output,
            format_args!(
                "  using _{}_type = {};\n",
                field.name,
                cpp_field_type(&field.field_type, field.multiplicity)
            ),
        );
    }
    // ROS 2's fluent setters: `msg.set__frame_id("map").set__seq(1)`.
    for field in &spec.fields {
        put(
            output,
            format_args!(
                "  {name}& set__{}(const _{}_type& _arg) {{\n    this->{} = _arg;\n    return *this;\n  }}\n",
                field.name,
                field.name,
                field_name_safe(&field.name)
            ),
        );
    }
    put(
        output,
        format_args!(
            "\n  bool operator==(const {name}&) const = default;\n\n  using Ptr = std::shared_ptr<{name}>;\n  using ConstPtr = std::shared_ptr<const {name}>;\n  using SharedPtr = std::shared_ptr<{name}>;\n  using ConstSharedPtr = std::shared_ptr<const {name}>;\n  using UniquePtr = std::unique_ptr<{name}>;\n\n  static constexpr const char* TYPE_NAME = \"{}\";\n  static constexpr const char* MD5 = \"{md5}\";\n}};\n\nusing {name}Ptr = {name}::Ptr;\nusing {name}ConstPtr = {name}::ConstPtr;\n// ROS 2 names the type through its allocator: {name}_<Allocator>.\ntemplate <class Allocator>\nusing {name}_ = {name};\n\n}}  // namespace {package}\n\n",
            spec.type_name.full()
        ),
    );
}

/// Writes one constant from its checked value. A constant the parser would refuse
/// becomes a `static_assert` that names it.
fn emit_constant(output: &mut String, constant: &Constant) {
    let Ok(value) = constant_value(constant) else {
        put(
            output,
            format_args!(
                "  static_assert(false, \"constant {} has no valid {} value\");\n",
                constant.name,
                constant.constant_type.render()
            ),
        );
        return;
    };
    let cpp_type = cpp_type_name(&constant.constant_type);
    let literal = match value {
        ConstantValue::Text(_) => {
            emit_text_constant(output, constant);
            return;
        }
        ConstantValue::Bool(flag) => String::from(if flag { "true" } else { "false" }),
        ConstantValue::Signed(number) if number == i64::MIN => {
            String::from("(-9223372036854775807LL - 1)")
        }
        ConstantValue::Signed(number) => number.to_string(),
        ConstantValue::Unsigned(number) if constant.constant_type == FieldType::UInt64 => {
            format!("{number}ULL")
        }
        ConstantValue::Unsigned(number) => number.to_string(),
        ConstantValue::Float(_) => constant.value.clone(),
    };
    put(output, format_args!("  static constexpr {cpp_type} {} = {literal};\n", constant.name));
}

fn emit_text_constant(output: &mut String, constant: &Constant) {
    let escaped = constant.value.replace('\\', "\\\\").replace('"', "\\\"");
    put(
        output,
        format_args!("  static constexpr const char* {} = \"{escaped}\";\n", constant.name),
    );
}

fn emit_message_traits(output: &mut String, spec: &MessageSpec, md5: &str, definition: &str) {
    let full_cpp_type = format!("::{}::{}", spec.type_name.package, spec.type_name.name);
    let is_fixed = is_spec_fixed_size(spec);
    let has_hdr = has_header(spec);
    output.push_str("namespace ros::message_traits {\n\n");
    let is_fixed_base = format!("std::bool_constant<{is_fixed}>");
    let has_hdr_base = format!("std::bool_constant<{has_hdr}>");
    for (trait_name, base) in [
        ("IsMessage", "std::true_type"),
        ("IsFixedSize", is_fixed_base.as_str()),
        ("HasHeader", has_hdr_base.as_str()),
    ] {
        for qualifier in ["", "const "] {
            put(
                output,
                format_args!(
                    "template <>\nstruct {trait_name}<{qualifier}{full_cpp_type}> : {base} {{}};\n\n"
                ),
            );
        }
    }
    let type_text = format!("\"{}\"", spec.type_name.full());
    let md5_text = format!("\"{md5}\"");
    let definition_text = escape_c_string(definition);
    for (trait_name, value) in
        [("DataType", type_text), ("MD5Sum", md5_text), ("Definition", definition_text)]
    {
        put(
            output,
            format_args!(
                "template <>\nstruct {trait_name}<{full_cpp_type}> {{\n  static const char* value() {{\n    return {value};\n  }}\n  static const char* value(const {full_cpp_type}&) {{\n    return value();\n  }}\n}};\n\n"
            ),
        );
    }
    output.push_str("}  // namespace ros::message_traits\n\n");
}

fn emit_serializer(output: &mut String, spec: &MessageSpec) {
    let full_cpp_type = format!("::{}::{}", spec.type_name.package, spec.type_name.name);
    output.push_str("namespace ros::serialization {\n\n");
    put(output, format_args!("template <>\nstruct Serializer<{full_cpp_type}> {{\n"));
    if spec.fields.is_empty() {
        output.push_str("  template <typename Stream, typename T>\n  inline static void allInOne(Stream& /*stream*/, T /*m*/) {}\n\n");
    } else {
        output.push_str("  template <typename Stream, typename T>\n  inline static void allInOne(Stream& stream, T m) {\n");
        for field in &spec.fields {
            put(output, format_args!("    stream.next(m.{});\n", field_name_safe(&field.name)));
        }
        output.push_str("  }\n\n");
    }
    output.push_str("  ROS_DECLARE_ALLINONE_SERIALIZER\n");
    output.push_str("};\n\n");
    output.push_str("}  // namespace ros::serialization\n");
}

/// The field `Publisher<M>::loan()` writes in place, when the message has one: its single
/// top-level variable-length array of numbers, if only fixed-size numbers follow it. A
/// message with two such arrays (`LaserScan`, `JointState`, `Joy`) has none, since the other
/// would have to be filled in the head. The fixed tail (`PointCloud2::is_dense`) is placed
/// after however many bytes the field turns out to hold.
fn loaned_field(spec: &MessageSpec) -> Option<&Field> {
    let is_number = |field_type: &FieldType| {
        !matches!(
            field_type,
            FieldType::Bool
                | FieldType::Text
                | FieldType::Time
                | FieldType::Duration
                | FieldType::Message(_)
        )
    };
    let is_number_array = |field: &Field| {
        field.multiplicity == Multiplicity::Variable && is_number(&field.field_type)
    };
    let mut arrays = spec.fields.iter().enumerate().filter(|(_, field)| is_number_array(field));
    let (position, field) = arrays.next()?;
    if arrays.next().is_some() {
        return None;
    }
    let fixed_tail = spec.fields.get(position.checked_add(1)?..)?.iter().all(|after| {
        let primitive = after.field_type == FieldType::Bool || is_number(&after.field_type);
        primitive && after.multiplicity != Multiplicity::Variable
    });
    fixed_tail.then_some(field)
}

fn emit_loaned_field(output: &mut String, spec: &MessageSpec) {
    let Some(field) = loaned_field(spec) else {
        return;
    };
    let full_cpp_type = format!("::{}::{}", spec.type_name.package, spec.type_name.name);
    put(
        output,
        format_args!(
            "\nnamespace hypha::message_traits {{\n\ntemplate <>\nstruct LoanedField<{full_cpp_type}> {{\n  static constexpr auto member = &{full_cpp_type}::{};\n}};\n\n}}  // namespace hypha::message_traits\n",
            field_name_safe(&field.name)
        ),
    );
}

/// `hypha::View<M>` for a message whose loaned field is an array of bytes: the message's
/// fields in its order, that one a `std::span` of the bytes it was received in. It is
/// moved, never copied, so that no copy of it outlives the bytes.
fn emit_view(output: &mut String, spec: &MessageSpec) {
    let Some(loaned) = loaned_field(spec) else {
        return;
    };
    let is_byte = matches!(
        loaned.field_type,
        FieldType::UInt8 | FieldType::Int8 | FieldType::Char | FieldType::Byte
    );
    if !is_byte {
        return;
    }
    let full_cpp_type = format!("::{}::{}", spec.type_name.package, spec.type_name.name);
    put(
        output,
        format_args!(
            "\n#include <span>\n\nnamespace hypha {{\n\n/// A received {} read in place (hypha/view.h).\ntemplate <>\nstruct View<{full_cpp_type}> {{\n  using Message = {full_cpp_type};\n\n",
            spec.type_name.full()
        ),
    );
    for field in &spec.fields {
        let field_type = if std::ptr::eq(field, loaned) {
            format!("std::span<const {}>", cpp_type_name(&field.field_type))
        } else {
            cpp_field_type(&field.field_type, field.multiplicity)
        };
        put(output, format_args!("  {field_type} {}{{}};\n", field_name_safe(&field.name)));
    }
    output.push_str(
        "\n  View() = default;\n  View(const View&) = delete;\n  View& operator=(const View&) = delete;\n  View(View&&) = default;\n  View& operator=(View&&) = default;\n  ~View() = default;\n};\n\n}  // namespace hypha\n",
    );
}

fn escape_c_string(s: &str) -> String {
    if s.is_empty() {
        return "\"\"".to_string();
    }
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n\"\n    \""),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The `IsFixedSize` value of `spec`, as C++, as ROS 1 gencpp computes it.
fn is_spec_fixed_size(spec: &MessageSpec) -> String {
    let mut nested = Vec::new();
    for field in &spec.fields {
        let is_variable = field.multiplicity == Multiplicity::Variable;
        if is_variable || field.field_type == FieldType::Text {
            return "false".to_string();
        }
        if matches!(field.field_type, FieldType::Message(_)) {
            let nested_type = cpp_type_name(&field.field_type);
            nested.push(format!("IsFixedSize<::{nested_type}>::value"));
        }
    }
    if nested.is_empty() {
        return "true".to_string();
    }
    nested.join(" && ")
}

fn has_header(spec: &MessageSpec) -> bool {
    let Some(first_field) = spec.fields.first() else {
        return false;
    };
    let is_unit_header =
        first_field.name == "header" && first_field.multiplicity == Multiplicity::Unit;
    is_unit_header
        && matches!(&first_field.field_type, FieldType::Message(type_name) if type_name.name == "Header")
}

/// Returns the C++ type name for any field type.
#[must_use]
fn cpp_type_name(field_type: &FieldType) -> String {
    match field_type {
        FieldType::Bool => "bool".to_string(),
        // ROS 1: `byte` is int8 and `char` is uint8.
        FieldType::Char | FieldType::UInt8 => "uint8_t".to_string(),
        FieldType::Byte | FieldType::Int8 => "int8_t".to_string(),
        FieldType::Int16 => "int16_t".to_string(),
        FieldType::UInt16 => "uint16_t".to_string(),
        FieldType::Int32 => "int32_t".to_string(),
        FieldType::UInt32 => "uint32_t".to_string(),
        FieldType::Int64 => "int64_t".to_string(),
        FieldType::UInt64 => "uint64_t".to_string(),
        FieldType::Float32 => "float".to_string(),
        FieldType::Float64 => "double".to_string(),
        FieldType::Text => "std::string".to_string(),
        FieldType::Time => "hypha_msgs::RosTime".to_string(),
        FieldType::Duration => "hypha_msgs::RosDuration".to_string(),
        FieldType::Message(type_name) => format!("{}::{}", type_name.package, type_name.name),
    }
}

/// Generates the C++ type and multiplicity wrapper for a field.
#[must_use]
fn cpp_field_type(field_type: &FieldType, multiplicity: Multiplicity) -> String {
    let base_type = cpp_type_name(field_type);

    match multiplicity {
        Multiplicity::Unit => base_type,
        Multiplicity::Variable => format!("std::vector<{base_type}>"),
        Multiplicity::Fixed(count) => format!("std::array<{base_type}, {count}>"),
    }
}

/// Returns the field name, with underscore suffix if it's a C++ keyword.
fn field_name_safe(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "class",
        "struct",
        "template",
        "typename",
        "namespace",
        "public",
        "private",
        "protected",
        "virtual",
        "operator",
        "new",
        "delete",
        "this",
        "int",
        "float",
        "double",
        "char",
        "bool",
        "void",
        "const",
        "static",
        "return",
        "if",
        "else",
        "for",
        "while",
        "switch",
        "case",
        "default",
        "break",
        "continue",
        "try",
        "catch",
        "throw",
        "using",
        "typedef",
        "union",
        "enum",
        "inline",
        "explicit",
        "friend",
        "mutable",
        "register",
        "signed",
        "unsigned",
        "short",
        "long",
        "auto",
    ];

    if KEYWORDS.contains(&name) { format!("{name}_") } else { name.to_string() }
}
