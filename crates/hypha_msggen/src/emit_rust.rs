//! Emitting Rust types and codecs from a message specification.

mod decode;
mod encode;

use crate::naming::camel_to_snake;
use crate::put;
use hypha_msgdef::constant::{ConstantValue, constant_value};
use hypha_msgdef::resolve::ServiceIdentity;
use hypha_msgdef::spec::{Constant, Field, FieldType, MessageSpec, Multiplicity, ServiceSpec};

/// The Rust sources generated for one service.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ServiceOutput {
    /// Request message source.
    pub request: String,
    /// Response message source.
    pub response: String,
    /// Service marker source.
    pub service: String,
}

/// Emit request, response, and service wrapper sources. Each half carries its own
/// MD5; the service marker carries the service MD5.
#[must_use]
pub fn emit_service(spec: &ServiceSpec, identity: &ServiceIdentity) -> ServiceOutput {
    let request = emit_message(&spec.request, &identity.request);
    let response = emit_message(&spec.response, &identity.response);
    let module = camel_to_snake(&spec.type_name.name);
    let name = &spec.type_name.name;
    let md5 = &identity.service;
    let service = format!(
        "//! Generated by hypha_msggen. Do not edit.\n\npub use super::{module}_request::{name}Request;\npub use super::{module}_response::{name}Response;\n\npub struct {name};\n\nimpl {name} {{\n    pub const MD5: &'static str = {md5:?};\n}}\n"
    );
    ServiceOutput { request, response, service }
}

/// Emits the Rust source for one message type.
#[must_use]
pub fn emit_message(spec: &MessageSpec, md5: &str) -> String {
    let mut out =
        format!("//! Generated from the `{}` definition. Do not edit.\n\n", spec.type_name.full());
    emit_imports(&mut out, spec);
    emit_struct(&mut out, spec);
    emit_impl(&mut out, spec, md5);
    let has_text_field = spec.fields.iter().any(|field| field.field_type == FieldType::Text);
    if has_text_field {
        decode::emit_decode_string_helper(&mut out);
    }

    out
}

fn emit_imports(out: &mut String, spec: &MessageSpec) {
    out.push_str("use hypha_core::message::{DecodeOwned, EncodeInto, MessageIdentity};\n");
    out.push_str("use hypha_wire::codec::{CodecError, Reader};\n");
    let has_time = spec.fields.iter().any(|field| field.field_type == FieldType::Time);
    let has_duration = spec.fields.iter().any(|field| field.field_type == FieldType::Duration);
    let time_types: Vec<&str> = [(has_duration, "RosDuration"), (has_time, "RosTime")]
        .into_iter()
        .filter_map(|(used, name)| used.then_some(name))
        .collect();
    if !time_types.is_empty() {
        put(out, format_args!("use hypha_wire::ros_time::{{{}}};\n", time_types.join(", ")));
    }
    out.push_str("use hypha_wire::slice_writer::SliceWriter;\n");
    let mut nested_types = spec.dependencies();
    nested_types.sort();
    nested_types.dedup();
    for nested in nested_types {
        let module = camel_to_snake(&nested.name);
        put(out, format_args!("use crate::{}::{module}::{};\n", nested.package, nested.name));
    }

    out.push('\n');
}

/// The `allow` line a struct or impl needs when a ROS field name is not snake case.
fn non_snake_allowance(spec: &MessageSpec) -> &'static str {
    let has_non_snake_field =
        spec.fields.iter().any(|field| field.name.chars().any(char::is_uppercase));
    if has_non_snake_field {
        "// ROS field names are part of the wire-facing public API.\n#[allow(non_snake_case)]\n"
    } else {
        ""
    }
}

fn emit_struct(out: &mut String, spec: &MessageSpec) {
    let name = &spec.type_name.name;
    let can_derive_default = spec
        .fields
        .iter()
        .all(|field| !matches!(field.multiplicity, Multiplicity::Fixed(count) if count > 32));
    let default_derive = if can_derive_default { ", Default" } else { "" };
    put(
        out,
        format_args!(
            "/// The `{}` message.\n#[derive(Debug, Clone, PartialEq{default_derive})]\n{}pub struct {name} {{\n",
            spec.type_name.full(),
            non_snake_allowance(spec)
        ),
    );

    for field in &spec.fields {
        put(
            out,
            format_args!(
                "    /// The `{}` field.\n    pub {}: {},\n",
                field.name,
                field_ident(&field.name),
                field_rust_type(field)
            ),
        );
    }

    out.push_str("}\n\n");

    if !can_derive_default {
        put(
            out,
            format_args!(
                "impl Default for {name} {{\n    fn default() -> Self {{\n        Self {{\n"
            ),
        );
        for field in &spec.fields {
            put(
                out,
                format_args!(
                    "            {}: {},\n",
                    field_ident(&field.name),
                    field_default(field)
                ),
            );
        }
        out.push_str("        }\n    }\n}\n\n");
    }
}

fn field_default(field: &Field) -> String {
    let field_type = &field.field_type;
    let unit = match field_type {
        FieldType::Bool => "false".to_string(),
        FieldType::Byte
        | FieldType::UInt8
        | FieldType::UInt16
        | FieldType::UInt32
        | FieldType::UInt64
        | FieldType::Char
        | FieldType::Int8
        | FieldType::Int16
        | FieldType::Int32
        | FieldType::Int64 => "0".to_string(),
        FieldType::Float32 | FieldType::Float64 => "0.0".to_string(),
        FieldType::Text => "::alloc::string::String::new()".to_string(),
        FieldType::Time => "RosTime::default()".to_string(),
        FieldType::Duration => "RosDuration::default()".to_string(),
        FieldType::Message(name) => format!("{}::default()", name.name),
    };
    match field.multiplicity {
        Multiplicity::Unit => unit,
        Multiplicity::Variable => "::alloc::vec::Vec::new()".to_string(),
        Multiplicity::Fixed(count) => match field_type {
            FieldType::Bool => format!("[{unit}; {count}]"),
            FieldType::Text | FieldType::Time | FieldType::Duration | FieldType::Message(_) => {
                format!("[const {{ {unit} }}; {count}]")
            }
            scalar => format!("[{unit}{}; {count}]", base_type(scalar)),
        },
    }
}

/// A field name as a Rust identifier: a keyword becomes a raw identifier.
fn field_ident(name: &str) -> String {
    if is_rust_keyword(name) { format!("r#{name}") } else { name.to_string() }
}

fn is_rust_keyword(name: &str) -> bool {
    matches!(
        name,
        "type"
            | "match"
            | "move"
            | "ref"
            | "fn"
            | "impl"
            | "let"
            | "mut"
            | "self"
            | "struct"
            | "enum"
            | "const"
            | "static"
            | "use"
            | "mod"
            | "pub"
            | "crate"
            | "where"
            | "loop"
            | "while"
            | "for"
            | "if"
            | "else"
            | "return"
            | "box"
            | "final"
            | "override"
    )
}

fn field_rust_type(field: &Field) -> String {
    let base = base_type(&field.field_type);
    match field.multiplicity {
        Multiplicity::Unit => base,
        Multiplicity::Variable => format!("::alloc::vec::Vec<{base}>"),
        Multiplicity::Fixed(count) => format!("[{base}; {count}]"),
    }
}

/// The Rust type of one element, also the suffix of its `read_` and `write_` calls.
fn base_type(field_type: &FieldType) -> String {
    match field_type {
        FieldType::Bool => "bool".to_string(),
        FieldType::Char | FieldType::UInt8 => "u8".to_string(),
        FieldType::Byte | FieldType::Int8 => "i8".to_string(),
        FieldType::Int16 => "i16".to_string(),
        FieldType::UInt16 => "u16".to_string(),
        FieldType::Int32 => "i32".to_string(),
        FieldType::UInt32 => "u32".to_string(),
        FieldType::Int64 => "i64".to_string(),
        FieldType::UInt64 => "u64".to_string(),
        FieldType::Float32 => "f32".to_string(),
        FieldType::Float64 => "f64".to_string(),
        FieldType::Text => "::alloc::string::String".to_string(),
        FieldType::Time => "RosTime".to_string(),
        FieldType::Duration => "RosDuration".to_string(),
        FieldType::Message(name) => name.name.clone(),
    }
}

/// Bytes one element of `field_type` occupies on the wire, when that is a constant.
fn fixed_width(field_type: &FieldType) -> Option<usize> {
    match field_type {
        FieldType::Bool
        | FieldType::Byte
        | FieldType::Char
        | FieldType::Int8
        | FieldType::UInt8 => Some(1),
        FieldType::Int16 | FieldType::UInt16 => Some(2),
        FieldType::Int32 | FieldType::UInt32 | FieldType::Float32 => Some(4),
        FieldType::Int64
        | FieldType::UInt64
        | FieldType::Float64
        | FieldType::Time
        | FieldType::Duration => Some(8),
        FieldType::Text | FieldType::Message(_) => None,
    }
}

/// True for an unsigned byte element (`char`, `uint8`), copied as one slice.
fn is_unsigned_byte(field_type: &FieldType) -> bool {
    matches!(field_type, FieldType::Char | FieldType::UInt8)
}

/// True for a signed byte element (`byte`, `int8`), read as one slice and converted to `i8`.
fn is_signed_byte(field_type: &FieldType) -> bool {
    matches!(field_type, FieldType::Byte | FieldType::Int8)
}

fn emit_impl(out: &mut String, spec: &MessageSpec, md5: &str) {
    out.push_str(non_snake_allowance(spec));
    put(out, format_args!("impl {} {{\n", spec.type_name.name));

    for constant in &spec.constants {
        emit_constant(out, constant);
    }

    put(
        out,
        format_args!(
            "    /// The full type name this struct was generated from.\n    pub const TYPE_NAME: &'static str = \"{}\";\n\n    /// The identity a receiver checks before decoding.\n    pub const SCHEMA_HASH: &'static str = \"{md5}\";\n\n",
            spec.type_name.full()
        ),
    );
    encode::emit_encoded_len_method(out, spec);
    encode::emit_encode_method(out, spec);
    decode::emit_decode_method(out, spec);

    out.push_str("}\n\n");
    emit_message_trait_impl(out, spec, md5);
}

fn emit_constant(out: &mut String, constant: &Constant) {
    let Some(type_str) = constant_type_name(&constant.constant_type) else {
        return;
    };

    put(
        out,
        format_args!(
            "    /// The `{name}` constant.\n    pub const {name}: {type_str} = {};\n\n",
            constant_value_text(constant, &type_str),
            name = constant.name
        ),
    );
}

fn constant_type_name(field_type: &FieldType) -> Option<String> {
    match field_type {
        FieldType::Text => Some("&'static str".to_string()),
        FieldType::Time | FieldType::Duration | FieldType::Message(_) => None,
        scalar => Some(base_type(scalar)),
    }
}

/// A constant written from its checked value. A constant the parser would refuse
/// becomes a `compile_error!` that names it.
fn constant_value_text(constant: &Constant, type_str: &str) -> String {
    let Ok(value) = constant_value(constant) else {
        return format!(
            "{{ compile_error!(\"constant {} has no valid {} value\") }}",
            constant.name,
            constant.constant_type.render()
        );
    };
    match value {
        ConstantValue::Text(text) => format!("{text:?}"),
        ConstantValue::Bool(flag) => flag.to_string(),
        ConstantValue::Signed(number) => number.to_string(),
        ConstantValue::Unsigned(number) => number.to_string(),
        ConstantValue::Float(number) => format!("{number:?}_{type_str}"),
    }
}

fn emit_message_trait_impl(out: &mut String, spec: &MessageSpec, md5: &str) {
    let name = &spec.type_name.name;
    let type_name = spec.type_name.full();

    put(
        out,
        format_args!(
            "impl MessageIdentity for {name} {{
    const TYPE_NAME: &'static str = \"{type_name}\";
    const SCHEMA_HASH: &'static str = \"{md5}\";
}}

impl EncodeInto for {name} {{
    fn encoded_len(&self) -> usize {{
        Self::encoded_len(self)
    }}

    fn encode_into(&self, buffer: &mut [u8]) -> Result<usize, CodecError> {{
        let mut writer = SliceWriter::new(buffer);
        Self::encode(self, &mut writer)?;
        Ok(writer.written())
    }}
}}

impl DecodeOwned for {name} {{
    fn decode_from(bytes: &[u8]) -> Result<Self, CodecError> {{
        let mut reader = Reader::new(bytes);
        Self::decode(&mut reader)
    }}
}}
"
        ),
    );
}
